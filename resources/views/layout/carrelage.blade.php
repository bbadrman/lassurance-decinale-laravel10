    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      II. Quelles garanties offre la garantie décennale carrelage ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      La garantie décennale carrelage couvre pendant 10 ans, à compter de la date de réception des
      travaux, les dommages qui compromettent la solidité de l'ouvrage ou qui, l'affectant dans l'un de
      ses éléments constitutifs ou l'un de ses éléments d'équipement indissociables, le rendent
      impropre à sa destination. Cette définition, posée par l'article 1792 du Code civil, constitue le
      périmètre légal minimal que tout contrat de décennale doit respecter.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Quels sinistres la garantie décennale carrelage prend-elle en charge ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Les sinistres pris en charge dans le cadre de la décennale carrelage sont ceux qui atteignent la
      solidité structurelle ou rendent le bien inhabitable ou inutilisable dans sa destination première.
      On peut citer, à titre d'exemples représentatifs : le décollement massif de carrelage de
      terrasse entraînant des infiltrations dans les parties communes d'un immeuble, le soulèvement de
      carrelage de sol porteur provoquant une rupture du revêtement structural, ou encore la
      fissuration d'un revêtement de façade carrelée compromettant l'étanchéité de l'enveloppe du
      bâtiment. Dans tous ces cas, l'assureur prend en charge le coût des travaux de réparation, y
      compris les frais de démolition, dépose et reconstruction.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. Quelles sont les exclusions fréquentes de la décennale carrelage ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Tout contrat d'assurance décennale carrelage comporte des exclusions contractuelles qu'il convient
      d'examiner attentivement avant la souscription. Les exclusions les plus courantes portent sur les
      dommages résultant d'une mauvaise utilisation par le maître d'ouvrage, d'un défaut d'entretien
      courant, ou d'une cause étrangère au travail réalisé (catastrophe naturelle reconnue à ce titre).
      Par ailleurs, les désordres purement esthétiques — rayures, différences de teinte entre carreaux —
      ne relèvent pas de la décenniale mais peuvent, selon leur gravité, être couverts par la garantie de
      parfait achèvement (1 an) ou la garantie biennale (2 ans). Nos experts analysent pour vous chaque
      contrat afin d'identifier ces zones d'ombre avant signature.
    </p>

