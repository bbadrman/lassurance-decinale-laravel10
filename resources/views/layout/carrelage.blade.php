    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      IV. Attestation décennale carrelage : comment l'obtenir et la remettre ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      L'attestation d'assurance décennale carrelage est le document officiel qui prouve, au maître d'ouvrage,
      que le professionnel est bien couvert avant l'ouverture du chantier. Sa remise est une obligation légale
      issue de l'article L241-1 du Code des assurances : le professionnel doit la fournir à chaque nouveau
      chantier, pour chaque contrat de louage d'ouvrage signé. Service-public.fr précise que cette attestation
      doit mentionner la période de validité du contrat, les activités couvertes et les coordonnées de l'assureur.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Que doit contenir une attestation décennale carrelage valide ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Une attestation décennale carrelage valide doit comporter, au minimum, les informations suivantes : le
      nom ou la raison sociale de l'assuré, le numéro SIRET, la dénomination de l'assureur et son numéro
      d'agrément ACPR, la période de validité du contrat, ainsi que les activités professionnelles couvertes —
      avec mention explicite de la pose de carrelage. Toute attestation ne mentionnant pas expressément
      l'activité de carrelage peut être refusée par le maître d'ouvrage ou par le contrôleur technique. Nos
      experts vérifient systématiquement la conformité des attestations délivrées avant de vous les transmettre.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. Que faire si l'on a été résilié par son assureur décennale ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      La résiliation d'un contrat décennale par l'assureur n'efface pas les garanties acquises sur les
      chantiers réceptionnés pendant la période de couverture. Conformément à l'article L113-12 du Code des
      assurances, la garantie décennale demeure effective pour les chantiers dont la réception est intervenue
      avant la date de résiliation, et ce pendant les 10 années qui suivent cette réception. En revanche, tout
      nouveau chantier ouvert après la résiliation n'est plus couvert : le professionnel doit impérativement
      souscrire un nouveau contrat avant de reprendre son activité. Nos experts accompagnent les professionnels
      en situation de résiliation pour identifier rapidement les assureurs acceptant ce profil de risque.
    </p>

