            ans les dommages compromettant la solidité ou la destination d'un ouvrage sur lequel des
            travaux de carrelage ont été réalisés. Elle est fondée sur les articles 1792 et suivants du
            Code civil. Tout carreleur professionnel — artisan, auto-entrepreneur ou société — doit
            souscrire ce contrat avant l'ouverture de chantier, et remettre son attestation au maître
