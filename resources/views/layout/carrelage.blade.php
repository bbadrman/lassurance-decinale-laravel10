    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      I. Décennale carrelage : Qu'est-ce que la décennale carrelage et qui est concerné ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      La décennale carrelage s'applique à tout professionnel qui réalise ou supervise des travaux de
      pose de carrelage sur un ouvrage de construction, qu'il soit entrepreneur individuel,
      auto-entrepreneur ou gérant de société. L'article 1792 du Code civil dispose que le constructeur
      est responsable de plein droit des dommages survenant dans les 10 ans suivant la réception des
      travaux, sans que le maître d'ouvrage ait à prouver une faute. Cette obligation ne souffre aucune
      exception : le statut juridique du professionnel ne modifie pas son obligation de couverture.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Le carreleur auto-entrepreneur est-il concerné par la décennale ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Un carreleur exerçant sous le régime de l'auto-entrepreneur est soumis aux mêmes obligations
      légales qu'un artisan classique. L'article L241-1 du Code des assurances ne distingue pas les
      statuts juridiques : dès lors que l'activité consiste à réaliser des travaux de construction à
      titre professionnel, la souscription d'une assurance décenniale est obligatoire avant l'ouverture
      de tout chantier. Le défaut d'assurance expose le professionnel à des sanctions pénales pouvant
      aller jusqu'à 75 000 € d'amende et 6 mois d'emprisonnement, conformément à l'article L243-3 du
      Code des assurances.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Imaginons un carreleur auto-entrepreneur qui intervient pour poser du carrelage dans une salle
      de bains d'une maison individuelle. Sans attestation décenniale remise au maître d'ouvrage, ce
      dernier est fondé à refuser le démarrage du chantier — et toute malfaçon apparaissant dans les 10
      ans suivant engage personnellement et financièrement le professionnel, sans couverture d'assurance
      pour y répondre.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. Quels travaux de carrelage relèvent de la garantie décennale ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Les travaux de carrelage entrent dans le champ de la garantie décenniale lorsqu'ils affectent la
      solidité de l'ouvrage ou le rendent impropre à sa destination. Selon la jurisprudence et les
      critères retenus par service-public.fr, sont notamment visés : le carrelage de sol porteur, les
      revêtements de terrasse avec risque d'infiltration, les carrelages de piscine et les revêtements
      de façade. En revanche, la simple pose de carrelage mural dans une cuisine sans lien avec la
      structure peut relever de la garantie biennale (2 ans) plutôt que décennale. La qualification
      précise dépend de la nature du désordre constaté.
    </p>

