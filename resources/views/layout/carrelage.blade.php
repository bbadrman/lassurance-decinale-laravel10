    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      III.. Prix décennale carreleur : Quel est le prix de la décennale carreleur ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      Le prix de l'assurance décennale carreleur varie en fonction du chiffre d'affaires annuel déclaré,
      de l'expérience du professionnel et du périmètre d'activité couvert par le contrat. Aucun barème
      légal ne fixe le tarif de la décennale : les primes résultent de la concurrence entre assureurs
      agréés par l'Autorité de contrôle prudentiel et de résolution (ACPR). Il est donc indispensable de
      comparer plusieurs offres avant de souscrire.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Quels critères influencent le tarif de la décennale carrelage ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Les assureurs retiennent plusieurs critères pour calculer la prime annuelle d'une décennale
      carrelage. Le premier est le chiffre d'affaires HT déclaré, qui sert de base de calcul au taux appliqué.
      Le second est la nature précise des travaux : un carreleur intervenant uniquement en intérieur présente
      un profil de risque différent d'un professionnel posant des carrelages de façade ou de piscine.
      L'expérience professionnelle et l'historique de sinistralité jouent également un rôle déterminant : un
      professionnel sans antécédent de sinistre bénéficie généralement de conditions tarifaires plus favorables.
      Enfin, le niveau de franchise retenu au contrat influe directement sur le montant de la prime.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Imaginons un carreleur artisan débutant son activité avec un chiffre d'affaires annuel prévisionnel
      modeste et une activité limitée à la pose de carrelage intérieur : son profil de risque sera considéré
      comme faible par les assureurs, ce qui se traduira par une prime plus accessible que pour un
      professionnel réalisant des terrasses et des façades carrelées de grande surface. Il est dans tous les
      cas recommandé de comparer au minimum 3 offres d'assureurs différents, tous référencés sur le registre
      ORIAS.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. Comment réduire le coût de sa décennale carreleur ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Plusieurs leviers permettent de maîtriser le prix de sa décennale carreleur sans réduire le niveau de
      protection. Déclarer avec précision et exhaustivement son périmètre d'activité évite les surprimes liées
      à une couverture trop large. Opter pour une franchise plus élevée fait baisser la prime annuelle, à
      condition de disposer d'une trésorerie suffisante pour l'assumer en cas de sinistre. Présenter des
      justificatifs de formation professionnelle (qualification Qualibat, mention au répertoire des métiers)
      peut également conduire certains assureurs à proposer des conditions préférentielles. Nos experts comparent
      les offres de plusieurs assureurs partenaires agréés ACPR pour vous proposer le contrat le mieux adapté à
      votre situation.
    </p>

