            L'assurance décenniale carrelage est-elle obligatoire ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700 mb-4">
            Oui, l'assurance décennale carrelage est obligatoire pour tout professionnel réalisant des
            travaux de carrelage à titre habituel, quel que soit son statut juridique. L'article L241-1 du
            Code des assurances impose cette obligation avant toute ouverture de chantier. Le maître
            d'ouvrage est en droit d'exiger l'attestation avant le début des travaux et de refuser l'accès
            au chantier en l'absence de ce document. L'absence d'assurance constitue un délit pénal
            passible de 75 000 € d'amende et de 6 mois d'emprisonnement selon l'article L243-3 du
            Code des assurances. Cette obligation s'applique également aux auto-entrepreneurs et aux
            micro-entrepreneurs exerçant l'activité de pose de carrelage.

          </p>

