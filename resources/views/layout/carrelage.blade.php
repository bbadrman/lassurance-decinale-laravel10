    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      V. Sinistre décennale carrelage : comment se déroule la procédure de mise en œuvre ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      En cas de sinistre relevant de la garantie décennale carrelage, la procédure légale impose des délais
      et des étapes précises que le maître d'ouvrage comme le professionnel doivent respecter. L'article
      1792-4-3 du Code civil précise que l'action en responsabilité décennale doit être intentée dans un délai
      de 10 ans à compter de la réception des travaux, délai de forclusion qui ne peut être suspendu que dans les
      cas limitativement prévus par la loi.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Comment déclarer un sinistre décennale carrelage ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      La déclaration de sinistre doit être adressée à l'assureur dommages-ouvrage (côté maître d'ouvrage) ou à
      l'assureur décenniale du carreleur, selon la voie choisie. Elle doit décrire avec précision la nature des
      désordres constatés, leur localisation et leur date d'apparition. L'assureur dispose d'un délai légal de
      60 jours pour désigner un expert, puis de 90 jours supplémentaires pour formuler une offre
      d'indemnisation, conformément aux dispositions de l'article L242-1 du Code des assurances relatif à
      l'assurance dommages-ouvrage. Ces délais sont impératifs et leur non-respect ouvre droit à majoration
      automatique de l'indemnité.
    </p>
    <p class="text-base text-gray-700 mb-6">
