    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Les éléments clés à vérifier dans un contrat de garantie décennale toiture
    </h3>
    <p class="text-base text-gray-700 mb-6">
      La souscription d'une garantie décennale toiture repose sur la déclaration précise de vos activités
      professionnelles. Un contrat souscrit pour une activité de couverture ne couvrira pas automatiquement des
      travaux de charpente ou d'étanchéité si ces activités n'ont pas été déclarées. Il est donc indispensable
      de vérifier que le libellé des activités garanties dans votre contrat correspond exactement à votre
      réalité terrain.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Plusieurs points contractuels méritent une attention particulière : le plafond de garantie par sinistre et
      par année de police, les clauses de franchise, les conditions de couverture des sous-traitants que vous
      mandatair, et la validité territoriale du contrat. Sur ce dernier point, une garantie limitée au
      territoire métropolitain peut poser un problème si vous intervenez dans les départements et régions
      d'outre-mer.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. L'attestation de garantie décennale toiture : document obligatoire avant tout chantier
    </h3>
    <p class="text-base text-gray-700 mb-6">
      L'attestation de garantie décennale toiture est le document que tout professionnel doit remettre au maître
      d'ouvrage avant le début des travaux. Cette obligation, posée par l'article L241-1 du Code des assurances,
      conditionne la validité de votre couverture en cas de sinistre. L'attestation doit mentionner les activités
      couvertes, la période de validité du contrat et le plafond de garantie. Selon service-public.fr, le maître
      d'ouvrage est en droit de refuser de signer tout contrat d'entreprise si cette attestation ne lui a pas été
      remise préalablement.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Nos experts comparent plusieurs offres du marché afin de vous proposer un contrat aligné sur vos activités
      réelles, sans sur-couverture inutile ni lacune préjudiciable. Un devis sans engagement vous permet d'évaluer
      les options disponibles avant toute décision.
    </p>

