        <h3 class="faq-question text-lg font-bold text-gray-900 mb-3">
          <span>
            <i class="fas fa-home text-yellow-500 mr-2"></i>
            C'est quoi la garantie décennale toiture exactement ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700 mb-4">
            La garantie décennale toiture est une assurance obligatoire qui engage la responsabilité du constructeur
            pendant 10 ans après la réception des travaux pour tout désordre affectant la solidité ou l'étanchéité de la
            toiture.
          </p>
          <p class="text-base text-gray-700">
            Son fondement juridique repose sur l'article 1792 du Code civil, issu de la loi Spinetta du 4 janvier 1978.
            Elle concerne tous les professionnels réalisant des travaux de couverture, de charpente ou d'étanchéité,
            quel que soit leur statut. Contrairement à la garantie de parfait achèvement, qui dure 1 an, ou à la garantie
            biennale, qui dure 2 ans, la garantie décennale couvre les désordres les plus graves sur une durée de 10 ans à
            compter du procès-verbal de réception signé par les deux parties.
          </p>
          <p class="text-base text-gray-700">
            <em>Référence : article 1792 du Code civil ; article 1792-6 du Code civil pour la garantie de parfait achèvement.</em>
