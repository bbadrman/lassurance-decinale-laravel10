  <div class="bg-white rounded-xl shadow-xl p-8">
    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      IV. Comment fonctionne la garantie décennale toiture en cas de sinistre ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      En cas de sinistre, la garantie décennale toiture s'active sur déclaration du maître d'ouvrage ou de son
      assureur dommages-ouvrage, à condition que le désordre soit constaté dans le délai de 10 ans courant à
      compter de la réception des travaux, acte formalisé par procès-verbal signé.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. La procédure de mise en jeu de la garantie décennale toiture
    </h3>
    <p class="text-base text-gray-700 mb-6">
      La mise en jeu de la garantie décennale toiture suit une procédure encadrée. Le maître d'ouvrage qui
      constate un désordre doit en premier lieu notifier le constructeur par lettre recommandée avec accusé de
      réception, en décrivant précisément la nature des dommages. Si le constructeur ne donne pas suite ou
      conteste sa responsabilité, le maître d'ouvrage peut saisir son assureur dommages-ouvrage, qui mandate
      alors un expert dans un délai fixé par l'article L242-1 du Code des assurances.
    </p>
    <p class="text-base text-gray-700 mb-6">
      L'expert désigné évalue la nature du sinistre, son lien avec les travaux réalisés et l'imputabilité au
      constructeur. En cas de reconnaissance du sinistre, l'assureur dommages-ouvrage préfinance les travaux de
      réparation, puis se retourne contre l'assureur en responsabilité décennale du constructeur dans le cadre
      d'un recours subrogatoire. Ce mécanisme, prévu par l'article L121-12 du Code des assurances, protège le
      maître d'ouvrage d'une attente procédurale qui peut s'étendre sur plusieurs années.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Imaginons un propriétaire qui constate, sept ans après la réception de sa toiture, des infiltrations
      importantes dans les combles. S'il a souscrit une assurance dommages-ouvrage, il peut obtenir une
      indemnisation dans un délai maîtrisé, sans attendre l'issue d'une procédure judiciaire contre l'entreprise
      de couverture. La garantie décennale du couvreur sera ensuite mobilisée par l'assureur dommages-ouvrage.
    </p>

