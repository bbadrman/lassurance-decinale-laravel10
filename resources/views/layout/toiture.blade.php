    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      III. Quels dommages sur la toiture sont couverts ou exclus par la garantie décennale ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      La garantie décennale toiture couvre les désordres qui compromettent la solidité de l'ouvrage ou le
      rendent impropre à sa destination, tels que définis par l'article 1792 du Code civil, mais elle exclut
      les dommages relevant de l'usure normale ou d'un défaut d'entretien.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Les désordres pris en charge par la garantie décennale toiture
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Sont couverts par la garantie décennale toiture tous les dommages d'une gravité suffisante pour affecter
      la solidité structurelle ou l'habitabilité du bâtiment. On distingue deux grandes catégories. Premièrement,
      les désordres atteignant la solidité de l'ouvrage : effondrement partiel ou total de la charpente,
      déformation structurelle excessive, rupture d'éléments porteurs. Deuxièmement, les désordres rendant
      l'ouvrage impropre à sa destination : infiltrations d'eau persistantes entraînant des dégâts sur les murs,
      plafonds ou planchers ; pont thermique structurel conduisant à une condensation généralisée ; défaut
      d'étanchéité sur toiture-terrasse causant des dommages aux parties inférieures du bâtiment.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. Les exclusions fréquentes de la garantie décennale toiture
    </h3>
    <p class="text-base text-gray-700 mb-6">
      La garantie décennale toiture ne couvre pas les dommages résultant d'une cause étrangère au constructeur :
      catastrophe naturelle reconnue par arrêté interministériel, défaut d'entretien manifeste du maître
      d'ouvrage, ou modification non autorisée de l'ouvrage par un tiers. Les dommages purement esthétiques —
      fissures superficielles, légère décoloration de tuiles — ne relèvent pas non plus de la garantie décennale,
      mais éventuellement de la garantie biennale de bon fonctionnement ou de la garantie de parfait achèvement
      d'un an prévue à l'article 1792-6 du Code civil.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Il est également important de noter que la garantie décennale ne se substitue pas à l'assurance
      dommages-ouvrage, souscrite quant à elle par le maître d'ouvrage en vertu de l'article L242-1 du Code des
      assurances. Ces deux mécanismes sont complémentaires : la dommages-ouvrage préfinance les réparations sans
      attendre la décision judiciaire, tandis que la garantie décennale définit la responsabilité du constructeur.
    </p>

