    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      I. Qu'est-ce que la garantie décennale toiture et quels travaux couvre-t-elle ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      La garantie décennale toiture est le mécanisme légal qui engage la responsabilité du constructeur pendant
      10 ans pour tout désordre compromettant la solidité de l'ouvrage ou le rendant impropre à sa destination.
      Elle s'applique dès lors que les travaux de toiture entrent dans le périmètre de l'article 1792 du Code
      civil.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Le périmètre des travaux soumis à la garantie décennale toiture
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Les travaux concernés par la garantie décennale toiture couvrent l'ensemble des ouvrages de couverture,
      dès lors qu'ils sont indissociables de la structure ou qu'ils participent à l'étanchéité globale du
      bâtiment. Concrètement, sont visés : la pose ou la réfection d'une couverture en tuiles, ardoises, zinc ou
      bac acier ; la réalisation d'une charpente industrielle ou traditionnelle ; les travaux d'étanchéité sur
      toiture-terrasse ; la pose de fenêtres de toit ou de velux en neuf ; et la mise en œuvre de systèmes
      d'évacuation des eaux pluviales intégrés à la structure.
    </p>
    <p class="text-base text-gray-700 mb-6">
      En revanche, les travaux d'entretien courant, nettoyage de gouttières, remplacement d'une tuile isolée
      ne relèvent pas de la garantie décennale, mais de la garantie de parfait achèvement ou de la
      responsabilité contractuelle de droit commun. La distinction est essentielle : selon service-public.fr,
      seuls les travaux de construction ou de rénovation lourde engagent la responsabilité décennale du
      constructeur.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Imaginons un artisan couvreur qui réalise la réfection complète d'une toiture en ardoises sur une maison
      individuelle. Si, dans les 5 ans suivant la réception, des infiltrations d'eau apparaissent en raison d'un
      défaut de pose, la garantie décennale s'applique de plein droit, sans que le maître d'ouvrage ait à
      démontrer la faute de l'artisan.
    </p>

