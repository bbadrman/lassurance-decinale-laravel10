    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      II. Qui est légalement obligé de souscrire une garantie décennale pour la toiture ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      Tout professionnel qui réalise des travaux de toiture à titre habituel est légalement tenu de souscrire
      une assurance de responsabilité décennale avant l'ouverture de tout chantier, conformément à l'article
      L241-1 du Code des assurances. Cette obligation s'impose sans exception au regard du statut juridique ou
      fiscal de l'intervenant.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Les professionnels concernés par l'obligation de garantie décennale toiture
    </h3>
    <p class="text-base text-gray-700 mb-6">
      L'obligation de garantie décennale toiture concerne tout professionnel du bâtiment intervenant sur des
      travaux de couverture, sans distinction de forme juridique. Elle vise les artisans couvreurs, zingueurs,
      charpentiers et étancheurs, qu'ils exercent en nom propre, en auto-entreprise, en EURL ou en SARL. Elle
      s'étend également aux sociétés de construction générale dès lors qu'elles sous-traitent ou réalisent
      elles-mêmes des travaux de toiture.
    </p>
    <p class="text-base text-gray-700 mb-6">
      L'article L241-1 du Code des assurances précise que « toute personne physique ou morale, dont la
      responsabilité décennale peut être engagée sur le fondement de la présomption établie par les articles
      1792 et suivants du Code civil, doit être couverte par une assurance ». Cette rédaction est inclusive :
      elle ne prévoit aucune exemption liée à la taille de l'entreprise, au chiffre d'affaires ou au régime
      fiscal.
    </p>
    <p class="text-base text-gray-700 mb-6">
      Prenons le cas hypothétique d'un auto-entrepreneur couvreur qui accepte un chantier de réfection de
      toiture sans avoir souscrit de garantie décennale. En cas de sinistre, non seulement sa responsabilité
      civile est engagée sur ses biens propres, mais il s'expose à une condamnation pénale pour exercice
      illégal, ainsi qu'à l'impossibilité de remettre une attestation au maître d'ouvrage, ce qui constitue en
      soi un manquement contractuel.
    </p>

