    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      IV. Qualification RGE et certification BTP : quelles obligations d'assurance spécifiques ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      La mention RGE (Reconnu Garant de l'Environnement) est une certification BTP spécifique qui conditionne
      l'éligibilité des travaux de rénovation énergétique aux aides de l'État, notamment MaPrimeRénov', les Certificats
      d'Économies d'Énergie (CEE) et l'éco-prêt à taux zéro. Elle est délivrée par Qualibat, Qualifelec ou d'autres
      organismes accrédités COFRAC, sous contrôle de l'ADEME et du Ministère de la Transition Écologique. La mention
      RGE ne modifie pas les obligations légales d'assurance, mais génère des exigences contractuelles spécifiques que
      tout titulaire doit connaître.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Pourquoi la mention RGE crée-t-elle des enjeux d'assurance particuliers ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Un professionnel RGE s'engage contractuellement à réaliser des travaux conformes à des critères de performance
      énergétique précis. En cas de non-atteinte des performances promises — par exemple une isolation thermique dont
      le coefficient Uc ne respecte pas les valeurs déclarées — la responsabilité civile professionnelle peut être
      engagée bien avant les 10 ans couverts par la garantie décennale. Il est donc indispensable que la RC pro d'un
      professionnel RGE couvre explicitement les travaux de rénovation énergétique dans leur nature et leurs exigences
      techniques. Nos experts vérifient systématiquement cette adéquation lors de l'étude de tout dossier RGE.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. Contrôle COFRAC et conséquences sur la couverture assurance
    </h3>
    <p class="text-base text-gray-700 mb-6">
      Le maintien de la mention RGE suppose un contrôle en cours de chantier réalisé sur au moins 10 % des chantiers
      par an, conformément aux exigences du dispositif RGE encadré par l'arrêté du 1er décembre 2015 modifié. Un
      retrait de mention RGE à la suite d'un contrôle défavorable peut avoir des conséquences sur les contrats
      d'assurance en cours si les travaux concernés avaient été déclarés sous la qualification RGE. L'assureur doit
      être informé de tout changement de qualification ou de certification dans les délais prévus à l'article L113-2
      du Code des assurances, qui impose au souscripteur de déclarer toute modification aggravant le risque.
    </p>

