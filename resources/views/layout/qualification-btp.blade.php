    <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
      II. Quel lien entre qualification certification BTP et assurance décennale obligatoire ?
    </h2>
    <p class="text-base text-gray-700 mb-6">
      La qualification certification BTP et l'assurance décennale sont deux dispositifs complémentaires qui se
      renforcent mutuellement : la qualification délimite le périmètre d'activité d'un professionnel, et l'assurance
      décennale couvre sa responsabilité civile sur ce même périmètre pendant 10 ans après réception des travaux.
      L'article L241-1 du Code des assurances pose l'obligation d'assurance décennale pour tout constructeur au sens
      de l'article 1792-1 du Code civil. Ces deux textes, issus de la loi du 4 janvier 1978 dite loi Spinetta, forment
      le socle légal incontournable de toute activité de construction en France.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      1. Pourquoi la qualification précise-t-elle le contenu de votre garantie décennale ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      L'assureur décennale base son évaluation du risque sur la nature exacte des travaux réalisés. La qualification
      BTP, en certifiant officiellement les corps de métier d'un professionnel, permet à l'assureur de définir
      précisément les activités déclarées dans le contrat. Un professionnel qui réalise des travaux hors de son
      domaine de qualification s'expose à une exclusion de garantie, voire à une nullité de contrat pour fausse
      déclaration du risque, conformément à l'article L113-8 du Code des assurances. C'est pourquoi nos experts
      insistent sur la nécessité d'aligner en permanence la qualification détenue et les activités déclarées dans
      la police d'assurance.
    </p>

    <h3 class="text-xl font-bold text-gray-900 mb-4 mt-8">
      2. Que se passe-t-il en cas d'absence d'assurance décennale pour un professionnel qualifié ?
    </h3>
    <p class="text-base text-gray-700 mb-6">
      L'absence d'assurance décennale constitue un délit pénal puni d'une amende pouvant atteindre 75 000 euros et
      d'une peine d'emprisonnement de 6 mois, conformément à l'article L243-3 du Code des assurances. Cette sanction
      s'applique quel que soit le niveau de qualification obtenu : la certification ne dispense pas de l'obligation
      d'assurance. En pratique, un maître d'ouvrage peut exiger la production de l'attestation d'assurance décennale
      avant le début de tout chantier, et le refus de la fournir entraîne l'impossibilité légale d'ouvrir le chantier.
      Service-public.fr rappelle d'ailleurs cette obligation de façon explicite dans sa rubrique dédiée aux
      professionnels du bâtiment.
    </p>

