      <!-- FAQ 1 -->
      <div class="faq-item border border-gray-200 rounded-xl p-6">
        <h3 class="faq-question text-lg font-bold text-gray-900 mb-3">
          <span>
            <i class="fas fa-gavel text-yellow-500 mr-2"></i>
            Qu'est-ce que le prix assurance décennale et comment est-il fixé ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700">
            Le prix assurance décennale est la prime annuelle versée par un professionnel du bâtiment pour couvrir sa responsabilité décennale obligatoire. Il est fixé par l'assureur sur la base de critères objectifs : nature des travaux, chiffre d'affaires déclaré, ancienneté de l'entreprise, niveau de franchise choisi et historique de sinistralité. L'obligation de souscrire ce contrat est fondée sur l'article L. 241-1 du Code des assurances et sur la loi n° 78-12 du 4 janvier 1978, telle que rappelée sur service-public.fr.
          </p>
        </div>
      </div>

      <!-- FAQ 2 -->
      <div class="faq-item border border-gray-200 rounded-xl p-6">
        <h3 class="faq-question text-lg font-bold text-gray-900 mb-3">
          <span>
            <i class="fas fa-euro-sign text-yellow-500 mr-2"></i>
            Combien coûte une assurance décennale pour un artisan ou un auto-entrepreneur ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700">
            Le coût d'une assurance décennale varie selon le corps de métier et le chiffre d'affaires déclaré : un auto-entrepreneur en corps d'état secondaire présentera un profil de risque différent d'un artisan en gros œuvre, ce qui se traduit par des primes distinctes. Il n'existe pas de tarif légalement fixé : chaque assureur applique sa propre grille tarifaire. Comparer au moins trois offres reste la démarche recommandée. La Fédération Française de l'Assurance (FFA) publie des données sectorielles sur la sinistralité en construction qui alimentent ces grilles. L'obligation s'applique dès le premier chantier, quel que soit le statut.
          </p>
        </div>
      </div>

      <!-- FAQ 3 -->
      <div class="faq-item border border-gray-200 rounded-xl p-6">
        <h3 class="faq-question text-lg font-bold text-gray-900 mb-3">
          <span>
            <i class="fas fa-user-check text-yellow-500 mr-2"></i>
            L'assurance décennale est-elle obligatoire pour tous les artisans du bâtiment ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700">
            Oui, l'assurance décennale est obligatoire pour tout professionnel réalisant des travaux soumis à la garantie décennale, qu'il soit artisan, auto-entrepreneur ou société, dès le premier chantier. L'article L. 241-1 du Code des assurances impose cette souscription avant l'ouverture du chantier. Le défaut d'assurance est sanctionné pénalement par l'article L. 243-3 du même code : jusqu'à 75 000 € d'amende et six mois d'emprisonnement. Service-public.fr précise que cette obligation concerne tous les constructeurs au sens de l'article 1792 du Code civil, sans exception liée au statut juridique ou au volume d'activité.
          </p>
        </div>
      </div>

      <!-- FAQ 4 -->
      <div class="faq-item border border-gray-200 rounded-xl p-6">
        <h3 class="faq-question text-lg font-bold text-gray-900 mb-3">
          <span>
            <i class="fas fa-bolt text-yellow-500 mr-2"></i>
            Comment obtenir un prix assurance décennale en ligne rapidement ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700">
            Pour obtenir un prix assurance décennale en ligne, il suffit de renseigner un formulaire de devis dématérialisé en indiquant le code APE, le chiffre d'affaires prévisionnel et la liste des activités exercées. Nos experts soumettent ensuite le dossier à plusieurs assureurs et restituent une comparaison structurée. Avant de transmettre des documents, vérifiez que l'intermédiaire figure au registre ORIAS (orias.fr), conformément aux obligations de l'article L. 512-1 du Code des assurances. Un devis en ligne ne vaut engagement ni pour l'assureur ni pour le professionnel.
          </p>
        </div>
      </div>

      <!-- FAQ 5 -->
      <div class="faq-item border border-gray-200 rounded-xl p-6">
        <h3 class="faq-question text-lg font-bold text-gray-900 mb-3">
          <span>
            <i class="fas fa-exchange-alt text-yellow-500 mr-2"></i>
            Peut-on trouver un prix assurance décennale même après une résiliation pour non-paiement ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700">
            Une résiliation pour non-paiement figure dans le relevé d'informations assurance (RIA) et peut complexifier la recherche d'un nouveau contrat décennal. Certains assureurs spécialisés proposent cependant des offres adaptées aux profils résiliés, sous réserve de déclaration complète de l'historique de sinistralité. L'article L. 113-3 du Code des assurances encadre strictement la procédure de résiliation pour non-paiement. En cas de difficulté, le Bureau Central de Tarification (BCT) peut contraindre un assureur à couvrir un professionnel qui ne trouve pas de contrat sur le marché, comme le prévoit l'article L. 212-1 du Code des assurances.
          </p>
        </div>
      </div>

      <!-- FAQ 6 -->
      <div class="faq-item border border-gray-200 rounded-xl p-6">
        <h3 class="faq-question text-lg font-bold text-gray-900 mb-3">
          <span>
            <i class="fas fa-clipboard-list text-yellow-500 mr-2"></i>
            Qu'est-ce qu'un comparatif prix assurance décennale doit obligatoirement inclure ?
          </span>
          <span class="faq-arrow">
            <i class="fas fa-chevron-down"></i>
          </span>
        </h3>
        <div class="faq-answer">
          <p class="text-base text-gray-700">
            Un comparatif prix assurance décennale sérieux doit inclure, pour chaque offre : le montant de la prime annuelle, le plafond de garantie par sinistre, la liste précise des activités couvertes, le montant et les modalités de la franchise, et les principales exclusions contractuelles. Se limiter à la prime sans examiner les garanties revient à comparer des prestations non équivalentes. L'article L. 112-2 du Code des assurances impose à tout assureur de remettre une notice d'information précisant ces éléments avant la signature. Nos experts réalisent ce travail d'analyse pour vous restituer une comparaison exploitable et complète.
          </p>
        </div>
