    <h3 class="text-xl font-bold text-gray-800 mb-4">1. Ce qu'un devis en ligne inclut réellement</h3>

    <p class="text-base text-gray-700 mb-4">
      Un devis prix assurance décennale en ligne doit obligatoirement indiquer, conformément à l'article L. 112-2 du Code des assurances, les garanties proposées, les exclusions applicables, le montant de la franchise et les modalités de résiliation. Trop souvent, les assurés comparent uniquement la prime annuelle sans examiner le plafond de garantie par sinistre ni la liste des exclusions contractuelles.
    </p>

    <p class="text-base text-gray-700 mb-4">
      Un contrat affichant une prime basse peut comporter des exclusions larges qui en réduisent significativement l'utilité en cas de sinistre. Nos experts analysent chaque proposition sur l'ensemble de ces paramètres, pas seulement sur le montant affiché. La démarche en ligne ne dispense pas d'une lecture attentive des conditions particulières, que le professionnel doit conserver pendant toute la durée de garantie décennale, soit dix ans après réception des travaux, conformément à ce que rappelle service-public.fr.
