  <!-- Section IV: Obligation -->
  <div class="bg-white rounded-xl shadow-xl p-8">
    <div class="text-center mb-8">
      <h2 class="text-2xl md:text-3xl font-bold text-gradient mb-6">
        IV. Qui est obligé de souscrire une assurance décennale ?
      </h2>
      <div class="w-16 lg:w-24 h-1 bg-amber-400 mx-auto rounded-full"></div>
    </div>

    <p class="text-lg text-gray-700 leading-relaxed mb-6">
      L'assurance décennale est obligatoire pour tout professionnel qui réalise des travaux de construction soumises à la garantie décennale au sens de l'article 1792 du Code civil. Cette obligation concerne toute personne physique ou morale qui, agissant en qualité de constructeur, conçoit, réalise ou fait réaliser des ouvrages de bâtiment, qu'elle soit artisan, société, auto-entrepreneur ou constructeur de maisons individuelles.
    </p>

    <h3 class="text-xl font-bold text-gray-800 mb-4">1. Les professionnels concernés par l'obligation</h3>

    <p class="text-base text-gray-700 mb-4">
      L'article L. 241-1 du Code des assurances énumère les personnes tenues à cette obligation : les entrepreneurs, les promoteurs immobiliers, les architectes, les maîtres d'œuvre et les techniciens liés au maître d'ouvrage par un contrat de louage d'ouvrage. Cette liste est extensive et comprend également les auto-entrepreneurs du bâtiment, contrairement à une idée répandue. Service-public.fr précise que l'obligation s'applique dès le premier chantier, indépendamment du statut juridique ou du chiffre d'affaires réalisé.
    </p>

    <h3 class="text-xl font-bold text-gray-800 mb-4">2. Les conséquences d'un défaut d'assurance</h3>

    <p class="text-base text-gray-700 mb-4">
      L'absence d'assurance décennale au moment de l'ouverture du chantier constitue une infraction pénale, sanctionnée par l'article L. 243-3 du Code des assurances d'une amende pouvant atteindre 75 000 € et d'une peine d'emprisonnement de six mois. Sur le plan civil, le professionnel non assuré reste intégralement responsable des désordres pendant dix ans et doit indemniser le maître d'ouvrage sur ses fonds propres.
    </p>

