    <p class="text-lg text-gray-700 leading-relaxed mb-6">
      Le comparatif prix assurance décennale met en évidence des écarts tarifaires significatifs entre assureurs pour un profil de risque identique, ce qui rend la mise en concurrence indispensable avant toute souscription. Comparer ne signifie pas uniquement retenir l'offre la moins chère : cela implique d'évaluer la qualité des garanties, la solidité financière de l'assureur et la qualité du service sinistre.
    </p>

    <h3 class="text-xl font-bold text-gray-800 mb-4">1. Les points de vigilance dans un comparatif</h3>

    <p class="text-base text-gray-700 mb-4">
      Lors d'un comparatif prix assurance décennale, quatre éléments méritent une attention particulière. Premièrement, le plafond de garantie par sinistre : la loi Spinetta n'impose pas de plafond minimum pour la garantie décennale elle-même, mais certains contrats low-cost limitent les indemnisations à des montants insuffisants au regard du coût réel des désordres structurels.
    </p>

    <p class="text-base text-gray-700 mb-4">
      Deuxièmement, la liste des activités garanties : il est impératif de vérifier que toutes les activités exercées — et pas seulement l'activité principale — figurent dans le contrat. Troisièmement, le traitement des sous-traitants : certains contrats excluent les dommages résultant de travaux confiés à des sous-traitants non déclarés. Quatrièmement, la clause de maintien en garantie après cessation d'activité, indispensable pour couvrir les sinistres déclarés après la dissolution de l'entreprise.
    </p>

    <h3 class="text-xl font-bold text-gray-800 mb-4">2. Scénario comparatif</h3>

    <p class="text-base text-gray-700 mb-4">
      Imaginons deux artisans électriciens, tous deux déclarant 80 000 € de chiffre d'affaires, l'un en première année d'activité, l'autre avec cinq ans d'ancienneté sans sinistre. Face à trois assureurs différents, ils pourraient obtenir des propositions dont les primes varient sensiblement d'un contrat à l'autre, non pas en raison d'une différence de qualité de couverture, mais parce que chaque assureur pondère différemment les critères d'ancienneté, de franchises et de périmètre d'activité.
    </p>

    <p class="text-base text-gray-700 mb-4">
      Ce scénario illustre pourquoi la comparaison sur un minimum de trois offres est une pratique recommandée par nos experts avant toute décision de souscription. La Fédération Française de l'Assurance (FFA) publie régulièrement des données sectorielles sur la sinistralité en construction, données qui alimentent les modèles tarifaires des assureurs. Ces statistiques agrégées, accessibles sur le site de la FFA, permettent de comprendre pourquoi certains corps de métier supportent des primes structurellement plus élevées que d'autres.
    </p>

