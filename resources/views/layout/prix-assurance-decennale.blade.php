    <p class="text-lg text-gray-700 leading-relaxed mb-6">
      Obtenir un devis prix assurance décennale adapté nécessite de suivre une démarche structurée en trois étapes : préparer les informations relatives à son activité, solliciter plusieurs assureurs ou un courtier enregistré à l'ORIAS, puis analyser les propositions sur l'ensemble des critères de couverture avant de signer.
    </p>

    <h3 class="text-xl font-bold text-gray-800 mb-4">1. La démarche recommandée étape par étape</h3>

    <p class="text-base text-gray-700 mb-4">
      La première étape consiste à définir précisément le périmètre d'activité : liste des corps de métier exercés, chiffre d'affaires prévisionnel, types de chantiers visés (logement individuel, logement collectif, bâtiment tertiaire, travaux sur existant).
    </p>

    <p class="text-base text-gray-700 mb-4">
      La seconde étape est la sollicitation de plusieurs offres : nos experts soumettent votre dossier à plusieurs assureurs et vous restituent une analyse comparative portant sur la prime, les garanties et les exclusions.
    </p>

    <p class="text-base text-gray-700 mb-4">
      La troisième étape est la validation contractuelle : avant la signature, vérifier que l'attestation d'assurance mentionne bien toutes les activités déclarées, car une activité omise pourrait ne pas être couverte en cas de sinistre.
    </p>

    <h3 class="text-xl font-bold text-gray-800 mb-4">2. L'attestation d'assurance : un document à conserver</h3>

    <p class="text-base text-gray-700 mb-4">
      L'attestation d'assurance décennale doit être remise au maître d'ouvrage avant l'ouverture du chantier, conformément à l'article L. 241-1 du Code des assurances. Ce document doit préciser le nom de l'assureur, le numéro du contrat, la période de validité et la liste des activités garanties.
    </p>

    <p class="text-base text-gray-700 mb-4">
      Service-public.fr rappelle que le maître d'ouvrage est en droit de refuser l'accès au chantier à tout professionnel qui ne peut présenter cette attestation. Conservez systématiquement une copie de chaque attestation annuelle émise, car la garantie décennale court dix ans après la réception des travaux, bien au-delà de la durée du contrat annuel.
    </p>

