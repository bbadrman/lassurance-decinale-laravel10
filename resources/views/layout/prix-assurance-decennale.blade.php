        I. Comment est calculé le prix assurance décennale ?
      </h2>
      <div class="w-16 lg:w-24 h-1 bg-amber-400 mx-auto rounded-full"></div>
    </div>

    <p class="text-lg text-gray-700 leading-relaxed mb-8">
      Le prix assurance décennale repose sur un ensemble de critères techniques et financiers que l'assureur évalue avant toute émission de contrat. Comprendre ces critères permet d'anticiper le montant de sa prime et d'éviter les mauvaises surprises lors du renouvellement.
    </p>

    <h3 class="text-xl font-bold text-gray-800 mb-4">1. Les critères déterminants du tarif</h3>

    <p class="text-base text-gray-700 mb-4">
      Le calcul du prix assurance décennale s'appuie sur au moins cinq variables objectives. Le premier facteur est la nature des travaux : les activités classées en corps d'état principaux (gros œuvre, charpente, couverture) exposent l'assureur à des sinistres structurels potentiellement lourds et génèrent donc une prime plus élevée que les corps d'état secondaires comme la peinture ou le carrelage. Le second facteur est le chiffre d'affaires annuel déclaré : la prime représente généralement un pourcentage de ce chiffre d'affaires, dont le taux varie selon la classe de risque attribuée à l'activité.
    </p>

    <p class="text-base text-gray-700 mb-4">
      Le troisième critère est l'expérience professionnelle : un artisan justifiant d'une longue pratique sans sinistre déclaré bénéficiera de conditions plus favorables qu'un professionnel nouvellement installé. Le quatrième facteur est le niveau des franchises choisies : opter pour une franchise plus élevée réduit mécaniquement la prime, mais augmente la part restant à la charge de l'assuré en cas de sinistre. Enfin, le périmètre géographique des interventions peut influencer le tarif, certains marchés étant jugés plus exposés.
    </p>

    <div class="bg-yellow-50 rounded-xl p-6 border-l-4 border-yellow-400 mb-6">
      <p class="text-base text-gray-700 italic">
        Prenons un scénario hypothétique : imaginons un artisan maçon déclarant 150 000 € de chiffre d'affaires annuel, sans sinistre sur les cinq dernières années. Son profil de risque sera perçu favorablement par les assureurs, ce qui peut se traduire par un taux de prime plus compétitif qu'un professionnel en première année d'activité sur le même corps de métier. Ces paramètres ne constituent pas un barème officiel mais illustrent la logique tarifaire du marché.
      </p>
    </div>

    

    <h3 class="text-xl font-bold text-gray-800 mb-4 mt-8">2. L'impact du code APE et de la qualification professionnelle</h3>

    <p class="text-base text-gray-700 mb-4">
      Le code APE (Activité Principale Exercée) attribué par l'INSEE conditionne directement la classification du risque par l'assureur. Deux artisans réalisant des travaux voisins peuvent se voir appliquer des taux différents si leurs codes APE correspondent à des familles de risque distinctes. Par ailleurs, la détention d'une qualification professionnelle reconnue — certificat de qualification professionnelle (CQP), label RGE ou équivalent — constitue un signal positif pour l'assureur, pouvant influer favorablement sur le tarif proposé.
    </p>

